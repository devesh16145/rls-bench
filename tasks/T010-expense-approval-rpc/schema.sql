create table public.departments (
  id bigint primary key,
  name text not null
);

create table public.department_members (
  department_id bigint not null references public.departments(id),
  user_id uuid not null references auth.users(id),
  is_manager boolean not null default false,
  primary key (department_id, user_id)
);

create table public.expenses (
  id bigint generated by default as identity primary key,
  department_id bigint not null references public.departments(id),
  submitted_by uuid not null references auth.users(id),
  amount numeric(10, 2) not null check (amount > 0),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  decided_by uuid references auth.users(id)
);

create index department_members_user_id_idx on public.department_members (user_id);
create index expenses_department_id_idx on public.expenses (department_id);
