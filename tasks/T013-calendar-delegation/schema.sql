create table public.events (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id),
  title text not null,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  is_private boolean not null default false,
  check (ends_at > starts_at)
);

create table public.delegations (
  grantor_id uuid not null references auth.users(id),
  delegate_id uuid not null references auth.users(id),
  can_edit boolean not null default false,
  expires_at timestamptz,
  primary key (grantor_id, delegate_id),
  check (grantor_id <> delegate_id)
);

create index events_owner_id_idx on public.events (owner_id);
create index delegations_delegate_id_idx on public.delegations (delegate_id);
