create table public.conversations (
  id bigint primary key,
  title text not null
);

create table public.participants (
  conversation_id bigint not null references public.conversations(id),
  user_id uuid not null references auth.users(id),
  primary key (conversation_id, user_id)
);

create table public.messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.conversations(id),
  sender_id uuid not null default auth.uid() references auth.users(id),
  body text not null,
  created_at timestamptz not null default '2020-01-01'
);

create table public.blocks (
  blocker_id uuid not null references auth.users(id),
  blocked_id uuid not null references auth.users(id),
  primary key (blocker_id, blocked_id),
  check (blocker_id <> blocked_id)
);

create index participants_user_id_idx on public.participants (user_id);
create index messages_conversation_id_idx on public.messages (conversation_id);
