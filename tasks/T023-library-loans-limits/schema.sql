create table public.books (
  id bigint primary key,
  title text not null,
  copies integer not null check (copies >= 0)
);

create table public.librarians (
  user_id uuid primary key references auth.users(id)
);

create table public.loans (
  id bigint generated by default as identity primary key,
  book_id bigint not null references public.books(id),
  borrower_id uuid not null default auth.uid() references auth.users(id),
  borrowed_on date not null default '2020-01-01',
  returned_on date
);

create index loans_book_id_idx on public.loans (book_id);
create index loans_borrower_id_idx on public.loans (borrower_id);
