create table public.boards (
  id bigint primary key,
  name text not null,
  is_archived boolean not null default false
);

create table public.board_members (
  board_id bigint not null references public.boards(id),
  user_id uuid not null references auth.users(id),
  role text not null check (role in ('viewer', 'editor')),
  primary key (board_id, user_id)
);

create table public.cards (
  id bigint generated by default as identity primary key,
  board_id bigint not null references public.boards(id),
  title text not null,
  column_name text not null default 'todo' check (column_name in ('todo', 'doing', 'done')),
  assignee_id uuid references auth.users(id)
);

create index board_members_user_id_idx on public.board_members (user_id);
create index cards_board_id_idx on public.cards (board_id);
