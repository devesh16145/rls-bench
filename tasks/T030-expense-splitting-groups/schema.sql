create table public.groups (
  id bigint primary key,
  name text not null
);

create table public.group_members (
  group_id bigint not null references public.groups(id),
  user_id uuid not null references auth.users(id),
  primary key (group_id, user_id)
);

create table public.expenses (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.groups(id),
  paid_by uuid not null default auth.uid() references auth.users(id),
  description text not null,
  amount numeric(10, 2) not null check (amount > 0)
);

create table public.expense_shares (
  expense_id bigint not null references public.expenses(id) on delete cascade,
  user_id uuid not null references auth.users(id),
  share numeric(10, 2) not null check (share >= 0),
  primary key (expense_id, user_id)
);
