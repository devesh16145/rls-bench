create table public.employees (
  user_id uuid primary key references auth.users(id),
  full_name text not null,
  manager_id uuid references public.employees(user_id)
);

create table public.leave_requests (
  id bigint generated by default as identity primary key,
  employee_id uuid not null default auth.uid() references public.employees(user_id),
  starts_on date not null,
  ends_on date not null,
  note text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'cancelled')),
  decided_by uuid references auth.users(id),
  check (ends_on >= starts_on)
);

create index leave_requests_employee_id_idx on public.leave_requests (employee_id);
