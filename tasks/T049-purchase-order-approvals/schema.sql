create table public.approvers (
  user_id uuid primary key references auth.users(id),
  limit_amount numeric(12, 2) not null
);

create table public.purchase_orders (
  id bigint generated by default as identity primary key,
  requester_id uuid not null default auth.uid() references auth.users(id),
  vendor text not null,
  amount numeric(12, 2) not null check (amount > 0)
);

create table public.po_approvals (
  po_id bigint primary key references public.purchase_orders(id),
  approver_id uuid not null references auth.users(id),
  decision text not null check (decision in ('approve', 'reject')),
  decided_at timestamptz not null default '2020-01-01'
);
