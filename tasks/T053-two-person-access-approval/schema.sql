create table public.ops_team (
  user_id uuid primary key references auth.users(id)
);

create table public.access_requests (
  id bigint generated by default as identity primary key,
  requester_id uuid not null default auth.uid() references auth.users(id),
  resource text not null,
  reason text not null,
  status text not null default 'pending' check (status in ('pending', 'granted'))
);

create table public.access_approvals (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.access_requests(id) on delete cascade,
  approver_id uuid not null references auth.users(id),
  approved_at timestamptz not null default '2020-01-01'
);
