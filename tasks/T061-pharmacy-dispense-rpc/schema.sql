create table public.pharmacists (
  user_id uuid primary key references auth.users(id)
);

create table public.prescriptions (
  id bigint primary key,
  patient_id uuid not null references auth.users(id),
  drug text not null,
  refills_left integer not null,
  expires_at timestamptz not null
);

create table public.dispenses (
  id bigint generated by default as identity primary key,
  prescription_id bigint not null references public.prescriptions(id),
  pharmacist_id uuid not null references auth.users(id),
  dispensed_at timestamptz not null default '2020-01-01'
);
