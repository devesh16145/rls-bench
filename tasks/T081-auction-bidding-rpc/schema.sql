create table public.auctions (
  id bigint primary key,
  seller_id uuid not null references auth.users(id),
  title text not null,
  starting_price numeric(10, 2) not null,
  min_increment numeric(10, 2) not null default 10,
  ends_at timestamptz not null,
  highest_bid numeric(10, 2),
  highest_bidder uuid references auth.users(id)
);

create table public.bids (
  id bigint generated by default as identity primary key,
  auction_id bigint not null references public.auctions(id),
  bidder_id uuid not null references auth.users(id),
  amount numeric(10, 2) not null,
  placed_at timestamptz not null default '2020-01-01'
);
