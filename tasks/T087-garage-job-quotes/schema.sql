create table public.garages (
  id bigint primary key,
  name text not null
);

create table public.mechanics (
  garage_id bigint not null references public.garages(id),
  user_id uuid not null references auth.users(id),
  primary key (garage_id, user_id)
);

create table public.jobs (
  id bigint generated by default as identity primary key,
  garage_id bigint not null references public.garages(id),
  customer_id uuid not null references auth.users(id),
  vehicle text not null,
  status text not null default 'quoted' check (status in ('quoted', 'approved', 'in_progress', 'done')),
  quote_amount numeric(10, 2) not null
);
