create table public.org_admins (
  org_id bigint not null,
  user_id uuid not null references auth.users(id),
  primary key (org_id, user_id)
);

create table public.devices (
  id bigint primary key,
  org_id bigint not null,
  assigned_to uuid references auth.users(id),
  name text not null
);

create table public.device_commands (
  id bigint generated by default as identity primary key,
  device_id bigint not null references public.devices(id),
  command text not null check (command in ('locate', 'lock', 'wipe')),
  issued_by uuid not null default auth.uid() references auth.users(id),
  issued_at timestamptz not null default '2020-01-01'
);
