create table public.reviewers (
  user_id uuid primary key references auth.users(id)
);

create table public.proposals (
  id bigint generated by default as identity primary key,
  speaker_id uuid not null default auth.uid() references auth.users(id),
  title text not null,
  abstract text not null default '',
  status text not null default 'submitted' check (status in ('submitted', 'accepted', 'rejected'))
);

create table public.reviews (
  proposal_id bigint not null references public.proposals(id),
  reviewer_id uuid not null default auth.uid() references auth.users(id),
  score integer not null check (score between 1 and 5),
  comment text not null default '',
  primary key (proposal_id, reviewer_id)
);
