create table public.bookings (
  id bigint primary key,
  student_id uuid not null references auth.users(id),
  tutor_id uuid not null references auth.users(id),
  status text not null check (status in ('requested', 'confirmed', 'cancelled'))
);

create table public.booking_messages (
  id bigint generated by default as identity primary key,
  booking_id bigint not null references public.bookings(id),
  sender_id uuid not null default auth.uid() references auth.users(id),
  body text not null
);
