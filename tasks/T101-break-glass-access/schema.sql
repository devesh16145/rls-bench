create table public.clinicians (
  user_id uuid primary key references auth.users(id)
);

create table public.auditors (
  user_id uuid primary key references auth.users(id)
);

create table public.patients (
  id bigint primary key,
  name text not null
);

create table public.care_team (
  patient_id bigint not null references public.patients(id),
  clinician_id uuid not null references auth.users(id),
  primary key (patient_id, clinician_id)
);

create table public.medical_records (
  id bigint primary key,
  patient_id bigint not null references public.patients(id),
  note text not null
);

create table public.break_glass_grants (
  id bigint generated by default as identity primary key,
  patient_id bigint not null references public.patients(id),
  clinician_id uuid not null references auth.users(id),
  reason text not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
