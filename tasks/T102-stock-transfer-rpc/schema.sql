create table public.warehouses (
  id bigint primary key,
  name text not null
);

create table public.warehouse_staff (
  warehouse_id bigint not null references public.warehouses(id),
  user_id uuid not null references auth.users(id),
  primary key (warehouse_id, user_id)
);

create table public.stock (
  warehouse_id bigint not null references public.warehouses(id),
  sku text not null,
  qty integer not null,
  primary key (warehouse_id, sku)
);

create table public.transfers (
  id bigint generated by default as identity primary key,
  from_warehouse bigint not null references public.warehouses(id),
  to_warehouse bigint not null references public.warehouses(id),
  sku text not null,
  qty integer not null,
  moved_by uuid not null references auth.users(id),
  moved_at timestamptz not null default now()
);
