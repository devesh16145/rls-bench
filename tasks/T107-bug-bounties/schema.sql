create table public.bounties (
  id bigint generated by default as identity primary key,
  title text not null,
  poster_id uuid not null default auth.uid() references auth.users(id),
  status text not null default 'open' check (status in ('open', 'awarded')),
  awarded_submission_id bigint
);

create table public.submissions (
  id bigint generated by default as identity primary key,
  bounty_id bigint not null references public.bounties(id),
  submitter_id uuid not null default auth.uid() references auth.users(id),
  body text not null default ''
);
