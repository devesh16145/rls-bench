create table public.cameras (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id),
  label text not null
);

create table public.camera_shares (
  id bigint generated by default as identity primary key,
  camera_id bigint not null references public.cameras(id),
  grantee_id uuid not null references auth.users(id),
  expires_at timestamptz,
  created_by uuid not null default auth.uid() references auth.users(id)
);

create table public.stream_keys (
  camera_id bigint primary key references public.cameras(id),
  key text not null
);
